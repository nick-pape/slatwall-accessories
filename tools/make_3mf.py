"""Pack STLs onto an MK4 bed and write a PrusaSlicer 3MF with an embedded print config.

    uv run python tools/make_3mf.py OUT.3mf tools/prusa/cfg.ini a.stl:4 b.stl:2
"""
import sys, zipfile
from pathlib import Path
import numpy as np, trimesh

BED = (250.0, 210.0)
GAP = 5.0
USAGE = "make_3mf.py OUT.3mf CONFIG.ini part.stl[:count] ..."
if len(sys.argv) < 4:
    sys.exit(USAGE)
OUT, CFG = Path(sys.argv[1]), Path(sys.argv[2])
PLATE = []                       # [(stl path, count)]
for a in sys.argv[3:]:
    f, _, c = a.partition(":")
    PLATE.append((Path(f), int(c or 1)))


def load(path):
    m = trimesh.load(path)
    m.apply_translation([-m.bounds[:, 0].mean(), -m.bounds[:, 1].mean(), -m.bounds[0, 2]])
    return m


def pack(items):
    """Shelf packing; items = [(key, w, d)] -> {idx: (cx, cy)}."""
    order = sorted(range(len(items)), key=lambda i: -items[i][2])
    pos, x, y, shelf_d = {}, GAP, GAP, 0.0
    for i in order:
        _, w, d = items[i]
        if x + w > BED[0] - GAP:
            x, y, shelf_d = GAP, y + shelf_d + GAP, 0.0
        pos[i] = (x + w / 2, y + d / 2)
        x += w + GAP
        shelf_d = max(shelf_d, d)
    if y + shelf_d > BED[1] - GAP:
        sys.exit(f"doesn't fit: needs {y + shelf_d:.0f} mm of {BED[1]}")
    # centre the whole layout on the bed
    xs = [p[0] for p in pos.values()]
    used_y = y + shelf_d + GAP
    dy = (BED[1] - used_y) / 2
    return {i: (cx, cy + dy) for i, (cx, cy) in pos.items()}, used_y


meshes = {n: load(n) for n, _ in PLATE}
items = []
for n, c in PLATE:
    w, d = meshes[n].extents[:2]
    items += [(n, w, d)] * c
pos, used = pack(items)
print(f"packed {len(items)} parts, {used:.0f}/{BED[1]} mm of bed depth used")

objs, build = [], []
oid = {n: k + 1 for k, (n, _) in enumerate(PLATE)}
name = {n: n.stem for n, _ in PLATE}
for n, _ in PLATE:
    m = meshes[n]
    v = "".join(f'<vertex x="{a:.5f}" y="{b:.5f}" z="{c:.5f}"/>' for a, b, c in m.vertices)
    t = "".join(f'<triangle v1="{a}" v2="{b}" v3="{c}"/>' for a, b, c in m.faces)
    objs.append(f'<object id="{oid[n]}" name="{name[n]}" type="model"><mesh><vertices>{v}</vertices>'
                f'<triangles>{t}</triangles></mesh></object>')
for i, (n, _, _) in enumerate(items):
    cx, cy = pos[i]
    build.append(f'<item objectid="{oid[n]}" transform="1 0 0 0 1 0 0 0 1 {cx:.4f} {cy:.4f} 0" printable="1"/>')

model = ('<?xml version="1.0" encoding="UTF-8"?>\n'
         '<model unit="millimeter" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02" '
         'xmlns:slic3rpe="http://schemas.slic3r.org/3mf/2017/06">\n'
         '<metadata name="slic3rpe:Version3mf">1</metadata>\n'
         f'<resources>{"".join(objs)}</resources>\n<build>{"".join(build)}</build>\n</model>\n')
model_cfg = ['<?xml version="1.0" encoding="UTF-8"?>\n<config>']
for n, c in PLATE:
    nf = len(meshes[n].faces)
    model_cfg.append(f'<object id="{oid[n]}" instances_count="{c}">'
                     f'<metadata type="object" key="name" value="{name[n]}"/>'
                     f'<volume firstid="0" lastid="{nf - 1}"><metadata type="volume" key="name" value="{name[n]}"/></volume></object>')
model_cfg.append('</config>\n')

with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
    z.writestr("[Content_Types].xml",
               '<?xml version="1.0" encoding="UTF-8"?>\n<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
               '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
               '<Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/></Types>')
    z.writestr("_rels/.rels",
               '<?xml version="1.0" encoding="UTF-8"?>\n<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
               '<Relationship Target="/3D/3dmodel.model" Id="rel-1" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>')
    z.writestr("3D/3dmodel.model", model)
    cfg = [l for l in CFG.read_text().splitlines() if l and not l.startswith("#")]
    z.writestr("Metadata/Slic3r_PE.config", "; generated by PrusaSlicer\n" + "".join(f"; {l}\n" for l in cfg))
    z.writestr("Metadata/Slic3r_PE_model.config", "".join(model_cfg))
print("wrote", OUT)
